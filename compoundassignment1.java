public class compoundassignment1 {
    public static void main(String[] args){
        int balence = 100;
        System.out.println(balence);                    //100
        System.out.println(balence = balence + 50);     //100+50=150
        System.out.println(balence);                    //150  bcz balence is updated  
        System.out.println(balence = balence - 50);     //150-50=100
        System.out.println(balence);                    //100
        
    }
    
}
